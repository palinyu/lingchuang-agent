function detectSeason(blob) {
  const t = String(blob || '');
  const seasons = Object.keys(SEASON_KEYS);
  for (let i = 0; i < seasons.length; i++) {
    const s = seasons[i];
    const keys = SEASON_KEYS[s];
    for (let j = 0; j < keys.length; j++) {
      if (t.indexOf(keys[j]) !== -1) return s;
    }
  }
  return null;
}

function pickMdStyle(poolKey, topic, usedNames, forceRelief) {
  const pool = MD_STYLE_POOLS[poolKey] || MD_STYLE_POOLS.default;
  let avail = pool.slice();
  if (forceRelief) {
    const relief = avail.filter(function (n) {
      return /浮雕|3D|3d|立体/.test(n);
    });
    if (relief.length) avail = relief;
  }
  if (usedNames && usedNames.length) {
    const filtered = avail.filter(function (n) {
      return usedNames.indexOf(n) === -1;
    });
    if (filtered.length) avail = filtered;
  }
  let h = 0;
  const seed = String(topic || '');
  for (let i = 0; i < seed.length; i++) h = (h << 5) - h + seed.charCodeAt(i);
  const idx = Math.abs(h) % avail.length;
  return avail[idx];
}

