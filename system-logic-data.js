function safeLower(blob) {
  return String(blob || '').toLowerCase();
}

function classifyMdCategory(blob, opts) {
  const lower = safeLower(blob);
  const options = opts || {};

  for (let i = 0; i < MD_LEGACY_OVERRIDES.length; i++) {
    const leg = MD_LEGACY_OVERRIDES[i];
    for (let j = 0; j < leg.keys.length; j++) {
      if (lower.indexOf(leg.keys[j].toLowerCase()) !== -1) {
        const cat = MD_CATEGORIES[leg.categoryId] || MD_CATEGORIES.education;
        return {
          categoryId: leg.categoryId,
          categoryName: cat.name,
          templateKey: leg.templateKey,
          technique: leg.technique,
          profile: leg.profile,
          matchedKey: leg.keys[j],
          isLegacy: true,
        };
      }
    }
  }

  let best = null;
  let bestScore = 0;
  let matchedKey = '';
  const ids = Object.keys(MD_CATEGORIES);
  for (let i = 0; i < ids.length; i++) {
    const id = ids[i];
    const cat = MD_CATEGORIES[id];
    let hit = 0;
    let first = '';
    for (let k = 0; k < cat.keys.length; k++) {
      if (lower.indexOf(cat.keys[k].toLowerCase()) !== -1) {
        hit++;
        if (!first) first = cat.keys[k];
      }
    }
    if (hit > bestScore) {
      bestScore = hit;
      best = cat;
      matchedKey = first;
    }
  }

  if (!best) {
    best = MD_CATEGORIES.education;
    matchedKey = '';
  }

  return {
    categoryId: best.id,
    categoryName: best.name,
    templateKey: best.id,
    technique: best.technique,
    profile: best.profile,
    matchedKey: matchedKey,
    isLegacy: false,
    isFallback: bestScore === 0,
  };
}

