/**
 * @param {string} text
 * @returns {string}
 */
function applyForbiddenFilter(text) {
  if (!text) return text;
  let out = String(text);
  for (let i = 0; i < FORBIDDEN_REPLACE_RULES.length; i++) {
    const pair = FORBIDDEN_REPLACE_RULES[i];
    const from = pair[0];
    const to = pair[1];
    if (!from) continue;
    out = out.split(from).join(to);
  }
  return out;
}

